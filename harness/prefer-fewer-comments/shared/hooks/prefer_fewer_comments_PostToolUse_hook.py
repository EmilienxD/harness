#!/usr/bin/env python3
"""
PostToolUse hook: prefer-fewer-comments. Runs on Claude Code and ChatGPT.

Fires after a write -- Write/Edit/MultiEdit, ChatGPT's `apply_patch`, or a
shell heredoc -- and reads only the text that call added. An oversized
comment, an oversized docstring, or a change that is more comment than code
leaves the write alone and returns `additionalContext` asking for less
commentary from here on.

Budgets live in DEFAULT_LIMITS, overridable per project in
`prefer-fewer-comments.rules`. Docstrings get a larger budget than comments
and a file header a larger one still: a contract and a module's purpose have
nowhere else to live, while an explanation of the code does.

It never blocks -- PostToolUse runs after the write -- and the reminder is
forward-looking: re-editing what is already written costs more than it saves,
while the next hundred lines are still unwritten. At most one reminder per
file every REMIND_INTERVAL_SECONDS, tracked in a per-session marker file.
"""
from __future__ import annotations

import difflib
import json
import os
import re
import sys
import tempfile
import time
from pathlib import Path
from typing import Any, Iterable

RULES_NAME = "prefer-fewer-comments.rules"

# Hook output strings are capped by both hosts; stay well under the limit.
MESSAGE_LIMIT = 4000

# At most this many findings are named per reminder; the rest become "+N more".
MAX_LISTED = 5

# One reminder per file per this many seconds: a burst of edits in one turn is
# a single reminder, an ignored one comes back while the work is still moving.
REMIND_INTERVAL_SECONDS = 180

DEFAULT_LIMITS = {
    "max-comment-lines": 2,
    "max-comment-chars": 240,
    "max-doc-lines": 5,
    "max-doc-chars": 600,
    # A file-header docstring says what the module is for, which nothing else
    # in the file can say, so it gets its own, larger budget.
    "max-header-lines": 15,
    "max-header-chars": 650,
    "max-comment-ratio": 0.30,
    "min-lines-for-ratio": 20,
}

EDIT_TOOLS = {"Write", "Edit", "MultiEdit"}
PATCH_TOOLS = {"apply_patch"}
SHELL_TOOLS = {"Bash", "PowerShell", "exec_command", "shell"}


# --- comment syntax ---------------------------------------------------------

class Family:
    """How one group of languages spells comments, docs and strings."""

    __slots__ = ("line", "doc_line", "block", "doc_block", "quotes", "triple")

    def __init__(self, line=(), doc_line=(), block=(), doc_block=(), quotes=(), triple=False):
        self.line = line              # line comment markers ("#", "//")
        self.doc_line = doc_line      # doc-comment markers, checked first ("///")
        self.block = block            # (open, close) pairs
        self.doc_block = doc_block    # (open, close) pairs, checked first ("/**")
        self.quotes = quotes          # string delimiters to skip over
        self.triple = triple          # Python-style triple-quoted docstrings


C_LIKE = Family(
    line=("//",),
    doc_line=("///", "//!"),
    block=(("/*", "*/"),),
    doc_block=(("/**", "*/"),),
    quotes=('"', "'", "`"),
)
HASH = Family(line=("#",), quotes=('"', "'"))
PYTHON = Family(line=("#",), quotes=('"', "'"), triple=True)
DASH = Family(line=("--",), block=(("--[[", "]]"),), quotes=('"', "'"))
MARKUP = Family(block=(("<!--", "-->"),))
LISP = Family(line=(";",), quotes=('"',))

# Extension -> family. Unknown extensions are skipped rather than guessed at:
# a wrong guess reports comments that aren't there.
EXTENSIONS: dict[str, Family] = {}
for _extensions, _family in (
    (
        "c h cc cpp cxx hpp hh cs java js jsx mjs cjs ts tsx go rs swift kt kts "
        "scala php dart m mm proto groovy zig sass scss less gradle v",
        C_LIKE,
    ),
    ("py pyi pyx", PYTHON),
    ("sh bash zsh fish ps1 psm1 rb pl pm r yaml yml toml tf cmake dockerfile mk nix ex exs", HASH),
    ("sql lua hs elm adb ads", DASH),
    ("html htm xml svg vue svelte md markdown mdx", MARKUP),
    ("clj cljs cljc el lisp scm ss rkt", LISP),
):
    for _extension in _extensions.split():
        EXTENSIONS[_extension] = _family

# Filenames without a useful extension.
BASENAMES = {"dockerfile": HASH, "makefile": HASH, "justfile": HASH, "rakefile": HASH}

# Machine-readable comments: directives, pragmas and linter controls. They are
# addressed to a tool rather than to a reader, so they are outside the budget.
DIRECTIVE = re.compile(
    r"^\s*(?:!|-\*-|type:|noqa|pragma|fmt:|ruff:|mypy:|pylint:|coding[:=]"
    r"|eslint|@ts-|prettier|jshint|globals|istanbul|c8 |v8 |biome-ignore"
    r"|go:|nolint|deadcode|codegen|Code generated by|swiftlint|clippy::"
    r"|@formatter:|region\b|endregion\b|\$FlowFixMe|#!)",
    re.IGNORECASE,
)


class Comment:
    __slots__ = ("kind", "start", "end", "text", "own_line", "merges")

    def __init__(self, kind: str, start: int, end: int, text: str, own_line: bool, merges: bool):
        self.kind = kind            # "doc" or "comment"
        self.start = start          # 0-based first line
        self.end = end              # 0-based last line
        self.text = text            # comment content, markers stripped
        self.own_line = own_line    # nothing but whitespace before the marker
        self.merges = merges        # a line comment, so adjacent ones form a block

    @property
    def lines(self) -> int:
        """Lines of prose, not lines spanned: a `/**` or `*/` on its own line
        is punctuation and shouldn't eat a jsdoc's budget."""
        return max(1, sum(1 for line in self.text.splitlines() if line.strip()))


def family_for(path: str) -> Family | None:
    name = path.replace("\\", "/").rsplit("/", 1)[-1].lower()
    _, _, extension = name.rpartition(".")
    if extension and extension in EXTENSIONS:
        return EXTENSIONS[extension]
    return BASENAMES.get(name)


def _line_start_blank(text: str, index: int) -> bool:
    """True when only whitespace separates *index* from the line's start."""
    start = text.rfind("\n", 0, index) + 1
    return not text[start:index].strip()


def _consume_string(text: str, index: int, quote: str) -> int:
    """Index just past the string literal opening at *index*."""
    position = index + len(quote)
    end = len(text)
    while position < end:
        character = text[position]
        if character == "\\":
            position += 2
            continue
        if text.startswith(quote, position):
            return position + len(quote)
        if character == "\n" and len(quote) == 1:
            return position  # unterminated: treat the newline as the end
        position += 1
    return end


def _triple_at(text: str, index: int) -> str | None:
    for quote in ('"""', "'''"):
        if text.startswith(quote, index):
            return quote
    return None


def scan_comments(text: str, family: Family) -> list[Comment]:
    """Every comment in *text*, in order, ignoring anything inside a string.

    Deliberately a lexer rather than a line matcher: `#` in a URL and `//` in
    a string are the two false positives that would make the whole reminder
    untrustworthy.
    """
    found: list[Comment] = []
    position, end, line = 0, len(text), 0

    def advance(stop: int) -> int:
        nonlocal line
        line += text.count("\n", position, stop)
        return stop

    while position < end:
        character = text[position]
        if character == "\n":
            line += 1
            position += 1
            continue

        if family.triple:
            quote = _triple_at(text, position)
            if quote is not None:
                own_line = _line_start_blank(text, position)
                close = text.find(quote, position + 3)
                stop = end if close == -1 else close + 3
                body = text[position + 3:close if close != -1 else end]
                start_line = line
                position = advance(stop)
                if own_line:
                    found.append(Comment("doc", start_line, line, body, True, False))
                continue

        matched = False
        for opener, closer in (*family.doc_block, *family.block):
            if not text.startswith(opener, position):
                continue
            kind = "doc" if (opener, closer) in family.doc_block else "comment"
            own_line = _line_start_blank(text, position)
            close = text.find(closer, position + len(opener))
            stop = end if close == -1 else close + len(closer)
            body = text[position + len(opener):close if close != -1 else end]
            start_line = line
            position = advance(stop)
            found.append(Comment(kind, start_line, line, body, own_line, False))
            matched = True
            break
        if matched:
            continue

        for marker in (*family.doc_line, *family.line):
            if not text.startswith(marker, position):
                continue
            kind = "doc" if marker in family.doc_line else "comment"
            own_line = _line_start_blank(text, position)
            stop = text.find("\n", position)
            stop = end if stop == -1 else stop
            body = text[position + len(marker):stop]
            found.append(Comment(kind, line, line, body, own_line, True))
            position = stop
            matched = True
            break
        if matched:
            continue

        if character in family.quotes:
            position = advance(_consume_string(text, position, character))
            continue

        position += 1

    return found


def blocks(comments: list[Comment]) -> list[Comment]:
    """Merge runs of adjacent own-line line comments into one block each."""
    merged: list[Comment] = []
    for comment in comments:
        previous = merged[-1] if merged else None
        if (
            previous is not None
            and previous.merges
            and comment.merges
            and previous.kind == comment.kind
            and previous.own_line
            and comment.own_line
            and comment.start == previous.end + 1
        ):
            previous.end = comment.end
            previous.text = f"{previous.text}\n{comment.text}"
            continue
        merged.append(
            Comment(comment.kind, comment.start, comment.end, comment.text,
                    comment.own_line, comment.merges)
        )
    return merged


# --- findings ---------------------------------------------------------------

def summarise(text: str) -> str:
    """First words of a comment, for naming it in the reminder."""
    flat = " ".join(text.split())
    return flat[:60] + ("..." if len(flat) > 60 else "")


def findings(text: str, added: set[int], family: Family, limits: dict[str, float]) -> list[str]:
    """Budget violations among the comments *added* touches.

    The whole text is scanned so comment state stays correct, then a comment
    counts only when the edit actually put one of its lines there.
    """
    results: list[tuple[int, str]] = []
    comment_lines = 0
    merged = blocks(scan_comments(text, family))
    header_until = first_code_line(text, merged)
    for comment in merged:
        touched = any(number in added for number in range(comment.start, comment.end + 1))
        if not touched:
            continue
        if DIRECTIVE.match(comment.text.strip()):
            continue
        body = " ".join(comment.text.split())
        header = comment.kind == "doc" and comment.start < header_until
        # The header is charged to its own budget, not to the file's density:
        # a short new file with a proper header is not a comment-heavy file.
        if comment.own_line and not header:
            comment_lines += comment.lines
        if header:
            max_lines, max_chars, label = (
                limits["max-header-lines"], limits["max-header-chars"], "file-header docstring"
            )
        elif comment.kind == "doc":
            max_lines, max_chars, label = limits["max-doc-lines"], limits["max-doc-chars"], "docstring"
        else:
            max_lines, max_chars, label = limits["max-comment-lines"], limits["max-comment-chars"], "comment"
        if comment.lines > max_lines:
            results.append((comment.start, f"line {comment.start + 1}: {comment.lines}-line {label} "
                                           f"(budget {int(max_lines)}) -- \"{summarise(body)}\""))
        elif len(body) > max_chars:
            results.append((comment.start, f"line {comment.start + 1}: {len(body)}-character {label} "
                                           f"(budget {int(max_chars)}) -- \"{summarise(body)}\""))

    added_code = sum(1 for number in added if _line_at(text, number).strip())
    if added_code >= limits["min-lines-for-ratio"]:
        ratio = comment_lines / added_code
        if ratio > limits["max-comment-ratio"]:
            results.append((-1, f"{comment_lines} of {added_code} added lines are comments "
                                f"({ratio:.0%}, budget {limits['max-comment-ratio']:.0%})"))

    results.sort(key=lambda item: item[0])
    return [description for _, description in results]


def first_code_line(text: str, comments: list[Comment]) -> int:
    """Line where code starts: anything above it is still the file header.

    A shebang, a coding line and a licence block sit above a module docstring,
    so "header" can't just mean line 1.
    """
    covered: set[int] = set()
    for comment in comments:
        covered.update(range(comment.start, comment.end + 1))
    for number, line in enumerate(text.splitlines()):
        if line.strip() and number not in covered:
            return number
    return len(text.splitlines())


def _line_at(text: str, number: int) -> str:
    lines = text.splitlines()
    return lines[number] if 0 <= number < len(lines) else ""


# --- what a tool call added -------------------------------------------------

def added_indices(old: str, new: str) -> set[int]:
    """Line numbers in *new* that *old* didn't have."""
    old_lines, new_lines = old.splitlines(), new.splitlines()
    added: set[int] = set()
    matcher = difflib.SequenceMatcher(None, old_lines, new_lines, autojunk=False)
    for tag, _, _, start, stop in matcher.get_opcodes():
        if tag in ("insert", "replace"):
            added.update(range(start, stop))
    return added


def every_line(text: str) -> set[int]:
    return set(range(len(text.splitlines())))


# Heredoc body, plus the file the surrounding command writes to.
HEREDOC = re.compile(r"<<-?\s*[\"']?(?P<tag>[A-Za-z_][A-Za-z0-9_]*)[\"']?\r?\n(?P<body>.*?)\r?\n[ \t]*(?P=tag)",
                     re.DOTALL)
REDIRECT_TARGET = re.compile(r">>?\s*(?![&>|])(?P<target>\"[^\"]*\"|'[^']*'|[^\s;&|)`<>]+)")
PATCH_FILE = re.compile(r"^\*\*\*\s+(?:Add|Update)\s+File:\s*(?P<path>.+?)\s*$")


def shell_changes(command: str) -> list[tuple[str, str, set[int]]]:
    """(path, text, added lines) for each heredoc the command writes to a file."""
    changes: list[tuple[str, str, set[int]]] = []
    for match in HEREDOC.finditer(command):
        tail = command[match.end():]
        target = REDIRECT_TARGET.search(tail.split("\n", 1)[0]) or REDIRECT_TARGET.search(
            command[:match.start()]
        )
        if target is None:
            continue
        path = target.group("target").strip("\"'")
        body = match.group("body")
        changes.append((path, body, every_line(body)))
    return changes


def patch_changes(patch: str) -> list[tuple[str, str, set[int]]]:
    """(path, added text, added lines) per file in an apply_patch payload.

    Only `+` lines are kept, so an unchanged comment in the context of a hunk
    is never reported. That splices lines that weren't adjacent on disk, which
    can merge two comments into one block -- acceptable, since a patch whose
    additions are that comment-dense is the case worth reporting anyway.
    """
    changes: list[tuple[str, str, set[int]]] = []
    path: str | None = None
    lines: list[str] = []

    def flush() -> None:
        if path and lines:
            body = "\n".join(lines)
            changes.append((path, body, every_line(body)))

    for raw in patch.splitlines():
        header = PATCH_FILE.match(raw)
        if header:
            flush()
            path, lines = header.group("path"), []
            continue
        if raw.startswith("*** "):
            flush()
            path, lines = None, []
            continue
        if path and raw.startswith("+"):
            lines.append(raw[1:])
    flush()
    return changes


def changes(event: dict[str, Any]) -> list[tuple[str, str, set[int]]]:
    """Every (path, text, added lines) triple this tool call produced."""
    name = event.get("tool_name")
    tool_input = event.get("tool_input")
    if not isinstance(tool_input, dict):
        return []

    if name in EDIT_TOOLS:
        path = tool_input.get("file_path") or tool_input.get("path")
        if not isinstance(path, str) or not path:
            return []
        if name == "Write":
            content = tool_input.get("content")
            return [(path, content, every_line(content))] if isinstance(content, str) else []
        edits = tool_input.get("edits") if name == "MultiEdit" else [tool_input]
        if not isinstance(edits, list):
            return []
        found = []
        for edit in edits:
            if not isinstance(edit, dict):
                continue
            new = edit.get("new_string")
            old = edit.get("old_string")
            if isinstance(new, str) and new:
                found.append((path, new, added_indices(old if isinstance(old, str) else "", new)))
        return found

    command = tool_input.get("command")
    if not isinstance(command, str) or not command:
        return []
    if name in PATCH_TOOLS or "*** Begin Patch" in command:
        return patch_changes(command)
    if name in SHELL_TOOLS:
        return shell_changes(command)
    return []


# --- rules ------------------------------------------------------------------

def compile_pattern(pattern: str) -> re.Pattern[str] | None:
    """Compile one gitignore-style pattern to a regex, or None if unusable.

    Same dialect as the sibling on-edit-block / on-edit-reminder tools: `*`
    within a segment, `?` for one character, `**` across segments, a leading
    `/` anchoring at the project root, a trailing `/` for a directory and
    everything under it.
    """
    pattern = pattern.strip().strip("\r")
    if pattern.startswith("/"):
        pattern = pattern[1:]
    directory = pattern.endswith("/")
    pattern = pattern.rstrip("/")
    if not pattern:
        return None
    anchored = "/" in pattern

    out: list[str] = []
    index, length = 0, len(pattern)
    while index < length:
        if pattern.startswith("**", index):
            segment = index == 0 or pattern[index - 1] == "/"
            after = pattern[index + 2:index + 3]
            if segment and after == "/":
                out.append("(?:[^/]+/)*")
                index += 3
            elif segment and index + 2 == length:
                out.append(".*")
                index += 2
            else:
                out.append("[^/]*")
                index += 2
        elif pattern[index] == "*":
            out.append("[^/]*")
            index += 1
        elif pattern[index] == "?":
            out.append("[^/]")
            index += 1
        else:
            out.append(re.escape(pattern[index]))
            index += 1
    body = "".join(out)
    if directory:
        body += "(?:/.*)?"
    if anchored:
        return re.compile("^" + body + "$")
    return re.compile("^(?:[^/]+/)*" + body + "$")


SETTING = re.compile(r"^(?P<key>[a-z-]+)\s*=\s*(?P<value>[0-9]*\.?[0-9]+)$")


def parse_rules(path: Path) -> tuple[dict[str, float], list[tuple[bool, re.Pattern[str]]]]:
    """(limit overrides, exemption patterns) from one rules file."""
    limits: dict[str, float] = {}
    patterns: list[tuple[bool, re.Pattern[str]]] = []
    try:
        text = path.read_text(encoding="utf-8-sig")
    except OSError:
        return limits, patterns
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        setting = SETTING.match(line)
        if setting and setting.group("key") in DEFAULT_LIMITS:
            limits[setting.group("key")] = float(setting.group("value"))
            continue
        negated = line.startswith("!")
        compiled = compile_pattern(line[1:] if negated else line)
        if compiled is not None:
            patterns.append((negated, compiled))
    return limits, patterns


def exempt(patterns: list[tuple[bool, re.Pattern[str]]], path: str) -> bool:
    """Last matching pattern wins; `!` puts a path back under the budget."""
    decision = False
    for negated, pattern in patterns:
        if pattern.match(path):
            decision = not negated
    return decision


def rules_sources(root: Path) -> list[Path]:
    """Global rules (next to the installed hook) first, then project rules."""
    sources: list[Path] = []
    seen: set[Path] = set()
    candidates = [Path(__file__).resolve().parent.parent / RULES_NAME]
    candidates += [root / directory / RULES_NAME for directory in (".claude", ".codex")]
    for candidate in candidates:
        try:
            key = candidate.resolve()
        except OSError:
            continue
        if key in seen or not candidate.is_file():
            continue
        seen.add(key)
        sources.append(candidate)
    return sources


# --- paths and session marker -----------------------------------------------

def project_root(event: dict[str, Any]) -> Path:
    root = os.environ.get("CLAUDE_PROJECT_DIR") or event.get("cwd")
    return Path(str(root)) if root else Path.cwd()


def normalise(path_text: str, root: Path) -> str:
    """Project-relative, forward-slash form, falling back to the basename."""
    if Path(path_text).is_absolute():
        try:
            return Path(path_text).resolve().relative_to(root.resolve()).as_posix()
        except (ValueError, OSError):
            return Path(path_text).name
    raw = path_text.replace("\\", "/")
    while raw.startswith("./"):
        raw = raw[2:]
    return raw


def marker_path(event: dict[str, Any]) -> Path | None:
    session = str(event.get("session_id") or "")
    safe = "".join(character for character in session if character.isalnum() or character in "-_")
    if not safe:
        return None
    return Path(tempfile.gettempdir()) / f"harness_prefer_fewer_comments_{safe}.marker"


def load_reminded(marker: Path | None) -> dict[str, float]:
    if marker is None:
        return {}
    reminded: dict[str, float] = {}
    try:
        text = marker.read_text(encoding="utf-8")
    except OSError:
        return reminded
    for line in text.splitlines():
        stamp, _, key = line.partition("\t")
        if not key.strip():
            continue
        try:
            reminded[key.strip()] = float(stamp)
        except ValueError:
            continue
    return reminded


def mark_reminded(marker: Path | None, reminded: dict[str, float], keys: Iterable[str], now: float) -> None:
    if marker is None:
        return
    updated = dict(reminded)
    for key in keys:
        updated[key] = now
    try:
        marker.write_text(
            "".join(f"{stamp}\t{key}\n" for key, stamp in sorted(updated.items())),
            encoding="utf-8",
        )
    except OSError:
        pass  # best-effort; worst case the same reminder repeats sooner


# --- output -----------------------------------------------------------------

def budget_line(limits: dict[str, float]) -> str:
    return (
        f"Budget: a comment up to {int(limits['max-comment-lines'])} lines or "
        f"{int(limits['max-comment-chars'])} characters, a docstring up to "
        f"{int(limits['max-doc-lines'])} lines, and under "
        f"{limits['max-comment-ratio']:.0%} comment lines in a change."
    )


def build_message(reported: list[tuple[str, list[str]]], limits: dict[str, float], first: bool) -> str:
    lines = []
    for path, items in reported:
        shown = items[:MAX_LISTED]
        extra = len(items) - len(shown)
        lines.append(f"`{path}`:")
        lines.extend(f"  - {item}" for item in shown)
        if extra:
            lines.append(f"  - +{extra} more")
    listing = "\n".join(lines)

    if not first:
        return f"Over the comment budget again:\n{listing}\n{budget_line(limits)}"

    return (
        "You just wrote more commentary than the code needs:\n"
        f"{listing}\n"
        f"{budget_line(limits)}\n"
        "Going forward in this session, write less of it. A comment earns its place by "
        "saying why something is done -- the constraint, the trade-off, the bug it avoids "
        "-- in a line or two. Restating what the code already says, narrating steps, and "
        "explaining the change you are making belong in the conversation, the commit "
        "message, or a doc, not in the file: the file is read by people who can read the "
        "code, and prose there rots the moment the code moves. Docstrings state a "
        "contract -- what goes in, what comes out, what surprises the caller -- not an "
        "essay. Clearer names and smaller functions replace most of what a long comment "
        "was trying to fix. What you already wrote stands; do not go back and rewrite it "
        "now, and cut it down next time you are in that code for another reason."
    )


def emit(event_name: str, message: str) -> None:
    print(json.dumps({
        "hookSpecificOutput": {
            "hookEventName": event_name,
            "additionalContext": message[:MESSAGE_LIMIT],
        }
    }))


def main() -> int:
    try:
        event = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        return 0
    if not isinstance(event, dict):
        return 0

    found = changes(event)
    if not found:
        return 0

    root = project_root(event)
    limits = dict(DEFAULT_LIMITS)
    patterns: list[tuple[bool, re.Pattern[str]]] = []
    for source in rules_sources(root):
        overrides, source_patterns = parse_rules(source)
        limits.update(overrides)
        patterns.extend(source_patterns)

    now = time.time()
    marker = marker_path(event)
    reminded = load_reminded(marker)

    reported: list[tuple[str, list[str]]] = []
    for path, text, added in found:
        family = family_for(path)
        if family is None or not added:
            continue
        relative = normalise(path, root)
        if exempt(patterns, relative):
            continue
        last = reminded.get(relative)
        if last is not None and now - last < REMIND_INTERVAL_SECONDS:
            continue
        items = findings(text, added, family, limits)
        if items:
            reported.append((relative, items))

    if not reported:
        return 0

    event_name = event.get("hook_event_name")
    if event_name not in ("PostToolUse", "PostToolUseFailure"):
        event_name = "PostToolUse"

    first = "delivered" not in reminded
    mark_reminded(marker, reminded, [path for path, _ in reported] + ["delivered"], now)
    emit(event_name, build_message(reported, limits, first))
    return 0


if __name__ == "__main__":
    sys.exit(main())
